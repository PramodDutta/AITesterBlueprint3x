"""Deterministic renderers and artifact writing.

Everything here is pure Python over validated Pydantic objects. No LLM output
is used as-is: the agents produce structured data, and these functions decide
exactly how it becomes Markdown, CSV, JSON, TypeScript and a ZIP.
"""

from __future__ import annotations

import csv
import io
import json
import zipfile
from datetime import datetime
from pathlib import Path

from ..models import (
    AutomationCandidate,
    CoverageReport,
    JiraIssue,
    PlaywrightBundle,
    RequirementAnalysis,
    RunSummary,
    TestCaseSuite,
    TestPlan,
    TicketResult,
    TicketStatus,
)
from .tickets import safe_path_segment

_GENERATED_NOTE = (
    "> Generated by Jira QA Crew. Every item traces to Jira content; anything "
    "marked INFERRED or ASSUMPTION_REQUIRING_CONFIRMATION needs human review "
    "before it is treated as fact."
)


