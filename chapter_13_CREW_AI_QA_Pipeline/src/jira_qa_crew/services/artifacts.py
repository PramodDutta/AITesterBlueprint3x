# --------------------------------------------------------------------------
def render_requirements_md(analysis: RequirementAnalysis, issue: JiraIssue | None = None) -> str:
    lines = [
        f"# Requirements Analysis — {analysis.ticket_key}",
        "",
        _GENERATED_NOTE,
        "",
        f"**Summary:** {analysis.summary}",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Issue type | {analysis.issue_type or 'not set'} |",
        f"| Status | {analysis.status or 'not set'} |",
        f"| Priority | {analysis.priority or 'not set'} |",
        f"| Labels | {', '.join(analysis.labels) or 'none'} |",
        f"| Components | {', '.join(analysis.components) or 'none'} |",
        f"| Parent | {analysis.parent or 'none'} |",
        f"| Subtasks | {', '.join(analysis.subtasks) or 'none'} |",
        f"| Linked issues | {', '.join(analysis.linked_issues) or 'none'} |",
        f"| Fetched via | {analysis.source.value} |",
    ]
    if issue and issue.url:
        lines.append(f"| Jira link | {issue.url} |")
    lines += ["", "## Description Summary", "", analysis.description_summary or "_none_", ""]

    lines += ["## Requirements", ""]
    if analysis.requirements:
        lines += ["| ID | Requirement | Category | Provenance | Source quote |", "| --- | --- | --- | --- | --- |"]
        for req in analysis.requirements:
            lines.append(
                f"| {req.id} | {_cell(req.text)} | {req.category} | "
                f"{req.provenance.value} | {_cell(req.source_quote) or '—'} |"
            )
    else:
        lines.append("_No requirements were extracted._")
    lines.append("")

    lines += ["## Acceptance Criteria", ""]
    if analysis.acceptance_criteria:
        lines += ["| ID | Criterion | Verifies | Provenance |", "| --- | --- | --- | --- |"]
        for criterion in analysis.acceptance_criteria:
            lines.append(
                f"| {criterion.id} | {_cell(criterion.text)} | "
                f"{', '.join(criterion.requirement_ids) or '—'} | {criterion.provenance.value} |"
            )
    else:
        lines.append(
            "_The ticket states no acceptance criteria. None were invented; "
            "see Missing Information._"
        )
    lines.append("")

    for title, values in (
        ("Business Rules", analysis.business_rules),
        ("Non-Functional Requirements", analysis.non_functional_requirements),
        ("Dependencies", analysis.dependencies),
        ("Constraints", analysis.constraints),
        ("Risks", analysis.risks),
        ("Assumptions (require confirmation)", analysis.assumptions),
        ("Missing Information", analysis.missing_information),
        ("Open Questions", analysis.open_questions),
    ):
        lines += [f"## {title}", ""]
        lines += [f"- {v}" for v in values] or ["_none recorded_"]
        lines.append("")
    return "\n".join(lines)


def render_test_plan_md(plan: TestPlan) -> str:
    lines = [f"# {plan.title}", "", _GENERATED_NOTE, "", f"**Ticket:** {plan.ticket_key}", ""]
    for section in plan.sections:
        lines += [f"## {section.number}. {section.title}", "", section.content.strip(), ""]
    if plan.scenarios:
        lines += ["## Scenario Index", "", "| ID | Scenario | Priority | Traces to |", "| --- | --- | --- | --- |"]
        for scenario in plan.scenarios:
            refs = ", ".join([*scenario.requirement_ids, *scenario.acceptance_criteria_ids])
            lines.append(
                f"| {scenario.id} | {_cell(scenario.title)} | {scenario.priority.value} | {refs} |"
            )
        lines.append("")
    return "\n".join(lines)


def render_test_cases_md(suite: TestCaseSuite) -> str:
    lines = [
        f"# Test Cases — {suite.ticket_key}",
        "",
        _GENERATED_NOTE,
        "",
        f"**Total test cases:** {len(suite.test_cases)}",
        "",
    ]
    if suite.coverage_notes:
        lines += ["## Coverage Notes", "", suite.coverage_notes.strip(), ""]

    for case in suite.test_cases:
        lines += [
            f"## {case.id} — {case.title}",
            "",
            f"- **Ticket:** {case.ticket_key}",
            f"- **Priority:** {case.priority.value}",
            f"- **Type:** {case.test_type.value}",
            f"- **Requirements:** {', '.join(case.requirement_ids) or '—'}",
            f"- **Acceptance criteria:** {', '.join(case.acceptance_criteria_ids) or '—'}",
            f"- **Automation candidate:** {case.automation_candidate.value}"
            + (f" — {case.automation_rationale}" if case.automation_rationale else ""),
            f"- **Tags:** {', '.join(case.tags) or '—'}",
            "",
            f"**Objective:** {case.objective or '—'}",
            "",
        ]
        if case.preconditions:
            lines += ["**Preconditions:**", *[f"- {p}" for p in case.preconditions], ""]
        if case.test_data:
            lines += ["**Test data:**", *[f"- {d}" for d in case.test_data], ""]
        lines += ["| # | Action | Expected |", "| --- | --- | --- |"]
        for step in case.steps:
            lines.append(f"| {step.number} | {_cell(step.action)} | {_cell(step.expected) or '—'} |")
        lines += ["", f"**Expected result:** {case.expected_result or '—'}", ""]
        if case.assumptions_or_blockers:
            lines += [
                "**Assumptions / blockers:**",
                *[f"- {b}" for b in case.assumptions_or_blockers],
                "",
            ]
    return "\n".join(lines)


def render_playwright_md(bundle: PlaywrightBundle) -> str:
    lang = {"ts": "typescript", "js": "javascript"}
    lines = [
        f"# Playwright Automation — {bundle.ticket_key}",
        "",
        _GENERATED_NOTE,
        "",
        f"**Automation readiness:** `{bundle.readiness.value}`",
        "",
    ]
    if bundle.readiness.value == "NEEDS_CONFIGURATION":
        lines += [
            "> This code compiles but is **not execution-ready**. The items under "
            "Missing Information must be supplied first.",
            "",
        ]
    if bundle.setup_notes:
        lines += ["## Setup", "", bundle.setup_notes.strip(), ""]

    if bundle.traces:
        lines += [
            "## Coverage",
            "",
            "| Test | Test case | Requirements | Acceptance criteria | File |",
            "| --- | --- | --- | --- | --- |",
        ]
        for trace in bundle.traces:
            lines.append(
                f"| {_cell(trace.test_name)} | {trace.test_case_id} | "
                f"{', '.join(trace.requirement_ids) or '—'} | "
                f"{', '.join(trace.acceptance_criteria_ids) or '—'} | {trace.spec_path or '—'} |"
            )
        lines.append("")

    lines += ["## Generated files", ""]
    for file in bundle.files:
        fence = lang.get(file.path.rsplit(".", 1)[-1], "typescript")
        lines += [f"### `{file.path}`", "", f"```{fence}", file.content.rstrip(), "```", ""]

    for title, values in (
        ("Missing Information", bundle.missing_information),
        ("Assumptions", bundle.assumptions),
    ):
        lines += [f"## {title}", ""]
        lines += [f"- {v}" for v in values] or ["_none_"]
        lines.append("")
    return "\n".join(lines)


def render_run_summary_md(run: RunSummary) -> str:
    lines = [
        "# Run Summary",
        "",
        f"**Run ID:** {run.run_id}",
        f"**Started:** {_stamp(run.started_at)}",
        f"**Finished:** {_stamp(run.finished_at)}",
        "",
        f"- Tickets requested: {len(run.requested_keys)}",
        f"- Completed: {len(run.completed)}",
        f"- Completed with warnings: {len(run.completed_with_warnings)}",
        f"- Failed: {len(run.failed)}",
        "",
    ]
    if run.invalid_inputs:
        lines += [f"- Rejected input tokens: {', '.join(run.invalid_inputs)}", ""]
    if run.duplicates_removed:
        lines += [f"- Duplicates removed: {', '.join(run.duplicates_removed)}", ""]

    lines += [
        "| Ticket | Status | Source | Automation | Requirements | Test cases | Coverage |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for result in run.results:
        coverage = (
            f"{result.coverage.requirement_coverage_pct}%" if result.coverage else "—"
        )
        lines.append(
            f"| {result.ticket_key} | {result.status.value} | "
            f"{result.source.value if result.source else '—'} | "
            f"{result.playwright.readiness.value if result.playwright else '—'} | "
            f"{result.coverage.total_requirements if result.coverage else 0} | "
            f"{result.coverage.total_test_cases if result.coverage else 0} | {coverage} |"
        )
    lines.append("")

    failures = run.failed
    if failures:
        lines += ["## Failures", ""]
        for result in failures:
            lines.append(f"- **{result.ticket_key}**: {result.error}")
        lines.append("")

    warned = [r for r in run.results if r.warnings]
    if warned:
        lines += ["## Warnings", ""]
        for result in warned:
            lines.append(f"- **{result.ticket_key}**")
            lines += [f"  - {w}" for w in result.warnings]
        lines.append("")
    return "\n".join(lines)


