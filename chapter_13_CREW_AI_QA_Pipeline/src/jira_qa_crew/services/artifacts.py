def render_test_cases_csv(suite: TestCaseSuite) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(
        [
            "test_case_id", "ticket_key", "title", "objective", "priority", "test_type",
            "requirement_ids", "acceptance_criteria_ids", "preconditions", "test_data",
            "steps", "expected_result", "automation_candidate", "automation_rationale",
            "tags", "assumptions_or_blockers",
        ]
    )
    for case in suite.test_cases:
        writer.writerow(
            [
                case.id, case.ticket_key, case.title, case.objective,
                case.priority.value, case.test_type.value,
                "; ".join(case.requirement_ids), "; ".join(case.acceptance_criteria_ids),
                " | ".join(case.preconditions), " | ".join(case.test_data),
                " | ".join(
                    f"{s.number}. {s.action}" + (f" -> {s.expected}" if s.expected else "")
                    for s in case.steps
                ),
                case.expected_result, case.automation_candidate.value,
                case.automation_rationale, "; ".join(case.tags),
                " | ".join(case.assumptions_or_blockers),
            ]
        )
    return buffer.getvalue()


def render_traceability_csv(coverage: CoverageReport) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(
        [
            "requirement_id", "requirement_text", "acceptance_criterion_id",
            "acceptance_criterion_text", "test_case_ids", "automated_test_case_ids",
            "coverage_status", "reason",
        ]
    )
    for row in coverage.rows:
        writer.writerow(
            [
                row.requirement_id, row.requirement_text, row.acceptance_criterion_id,
                row.acceptance_criterion_text, "; ".join(row.test_case_ids),
                "; ".join(row.automated_test_case_ids), row.coverage_status.value, row.reason,
            ]
        )
    return buffer.getvalue()


