def build_ticket_manifest(result: TicketResult) -> dict:
    coverage = result.coverage
    return {
        "ticket_key": result.ticket_key,
        "status": result.status.value,
        "source": result.source.value if result.source else None,
        "jira_url": result.issue.url if result.issue else "",
        "fetched_at": _stamp(result.issue.fetched_at) if result.issue else None,
        "started_at": _stamp(result.started_at),
        "finished_at": _stamp(result.finished_at),
        "duration_seconds": result.duration_seconds,
        "counts": {
            "requirements": len(result.analysis.requirements) if result.analysis else 0,
            "acceptance_criteria": (
                len(result.analysis.acceptance_criteria) if result.analysis else 0
            ),
            "test_cases": len(result.test_cases.test_cases) if result.test_cases else 0,
            "automation_candidates": (
                len(
                    [
                        c
                        for c in result.test_cases.test_cases
                        if c.automation_candidate is not AutomationCandidate.NO
                    ]
                )
                if result.test_cases
                else 0
            ),
            "playwright_files": len(result.playwright.files) if result.playwright else 0,
        },
        "coverage": (
            {
                "requirement_coverage_pct": coverage.requirement_coverage_pct,
                "automation_pct": coverage.automation_pct,
                "covered_requirements": coverage.covered_requirements,
                "partially_covered_requirements": coverage.partially_covered_requirements,
                "uncovered_requirements": coverage.uncovered_requirements,
                "orphan_requirement_ids": coverage.orphan_requirement_ids,
                "orphan_test_case_ids": coverage.orphan_test_case_ids,
                "unknown_reference_ids": coverage.unknown_reference_ids,
            }
            if coverage
            else None
        ),
        "automation_readiness": (
            result.playwright.readiness.value if result.playwright else None
        ),
        "missing_information": (
            result.playwright.missing_information if result.playwright else []
        ),
        "warnings": result.warnings,
        "error": result.error,
        "artifacts": result.artifacts,
        "stages": [
            {
                "stage": s.stage.value,
                "status": s.status.value,
                "message": s.message,
                "duration_seconds": s.duration_seconds,
            }
            for s in result.stages
        ],
    }


def build_run_manifest(run: RunSummary) -> dict:
    return {
        "run_id": run.run_id,
        "generator": "Jira QA Crew",
        "started_at": _stamp(run.started_at),
        "finished_at": _stamp(run.finished_at),
        "requested_keys": run.requested_keys,
        "invalid_inputs": run.invalid_inputs,
        "duplicates_removed": run.duplicates_removed,
        "totals": {
            "requested": len(run.requested_keys),
            "completed": len(run.completed),
            "completed_with_warnings": len(run.completed_with_warnings),
            "failed": len(run.failed),
        },
        "successful": run.successful,
        "tickets": [build_ticket_manifest(r) for r in run.results],
    }


